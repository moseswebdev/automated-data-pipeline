"""
SYNTHETIC DATA GENERATOR FOR AUTOMATED DATA PIPELINE.

Notice: All datasets generated by this script (products, stores, transactions,
and inventory) are 100% synthetic and procedurally generated for testing,
development, and demonstration purposes. No real customer, store, or sales
records are used.
"""

import pandas as pd
import numpy as np
import random
import string
from datetime import datetime, timedelta
from pathlib import Path

# Set global seeds for reproducibility
RANDOM_SEED = 42
random.seed(RANDOM_SEED)
np.random.seed(RANDOM_SEED)


def generate_products(num_products: int = 1000) -> pd.DataFrame:
    """
    Generate a synthetic catalog of retail products.

    Methodology:
    - Product IDs follow a sequential 'PROD-XXXX' format.
    - Names are constructed by combining realistic adjectives, product types,
      and alphanumeric model codes across five retail categories.
    - Base prices are sampled using a log-normal distribution to reflect
      real-world retail pricing (many low-to-mid priced items, fewer luxury items).
    - Popularity weights are drawn from a Pareto distribution so a small subset
      of products drive the majority of sales (80/20 rule).
    """
    categories = {
        "Electronics": ["Headphones", "Smartwatch", "Speaker", "Monitor", "Keyboard", "Camera"],
        "Clothing": ["Jacket", "Sneakers", "T-Shirt", "Jeans", "Sweater", "Backpack"],
        "Home & Kitchen": ["Coffee Maker", "Blender", "Desk Lamp", "Cookware Set", "Air Purifier", "Vacuum"],
        "Sports & Outdoors": ["Yoga Mat", "Dumbbell Set", "Tent", "Running Shoes", "Water Bottle", "Bicycle Helmet"],
        "Books & Media": ["Hardcover Novel", "Cookbook", "Board Game", "Vinyl Record", "Tech Manual", "Journal"],
    }
    adjectives = ["Pro", "Ultra", "Eco", "Classic", "Smart", "Compact", "Deluxe", "Essential", "Lite", "Max"]

    records = []
    # Pareto weights to simulate realistic product popularity skew
    popularity_weights = np.random.pareto(a=1.5, size=num_products) + 1.0
    popularity_weights /= popularity_weights.sum()

    for i in range(1, num_products + 1):
        category = random.choice(list(categories.keys()))
        item_type = random.choice(categories[category])
        adj = random.choice(adjectives)
        model_code = "".join(random.choices(string.ascii_uppercase + string.digits, k=3))

        # Log-normal price distribution bounded between $5.00 and $1,500.00
        raw_price = np.random.lognormal(mean=3.5, sigma=0.8)
        unit_price = round(float(np.clip(raw_price, 5.0, 1500.0)), 2)

        records.append({
            "product_id": f"PROD-{i:04d}",
            "product_name": f"{adj} {item_type} {model_code}",
            "category": category,
            "unit_price": unit_price,
            "popularity_weight": popularity_weights[i - 1],
        })

    return pd.DataFrame(records)


def generate_stores(num_stores: int = 100) -> pd.DataFrame:
    """
    Generate a synthetic table of retail store locations.

    Methodology:
    - Store IDs follow a sequential 'STORE-XXX' format.
    - Stores are distributed across major US cities and regions with assigned
      store formats (Flagship, Standard, Express).
    - Traffic multipliers are assigned based on store format and random variation
      to model realistic differences in store-level sales volume.
    """
    locations = [
        ("New York", "NY", "Northeast"), ("Boston", "MA", "Northeast"), ("Philadelphia", "PA", "Northeast"),
        ("Chicago", "IL", "Midwest"), ("Detroit", "MI", "Midwest"), ("Minneapolis", "MN", "Midwest"),
        ("Atlanta", "GA", "South"), ("Miami", "FL", "South"), ("Dallas", "TX", "South"), ("Austin", "TX", "South"),
        ("Los Angeles", "CA", "West"), ("San Francisco", "CA", "West"), ("Seattle", "WA", "West"), ("Denver", "CO", "West"),
    ]
    store_tiers = [
        ("Flagship", 2.5),
        ("Standard", 1.0),
        ("Express", 0.5),
    ]

    records = []
    for i in range(1, num_stores + 1):
        city, state, region = random.choice(locations)
        tier_name, base_multiplier = random.choices(store_tiers, weights=[0.15, 0.60, 0.25], k=1)[0]

        # Add +/- 20% organic store-to-store traffic variance
        traffic_weight = round(base_multiplier * random.uniform(0.8, 1.2), 4)

        records.append({
            "store_id": f"STORE-{i:03d}",
            "store_name": f"{city} {tier_name} #{i}",
            "city": city,
            "state": state,
            "region": region,
            "store_tier": tier_name,
            "traffic_weight": traffic_weight,
        })

    df = pd.DataFrame(records)
    df["traffic_weight"] = df["traffic_weight"] / df["traffic_weight"].sum()
    return df


def generate_customer_ids(num_customers: int = 12000) -> np.ndarray:
    """
    Generate an array of unique synthetic customer identifiers.

    Methodology:
    - Produces alphanumeric customer IDs formatted as 'CUST-XXXXXX'.
    - Used as a customer pool so repeat purchases occur naturally across
      the 50,000 transaction records.
    """
    return np.array([f"CUST-{i:06d}" for i in range(1, num_customers + 1)])


def generate_timestamps(num_records: int, end_date: datetime) -> list[datetime]:
    """
    Generate realistic transaction timestamps spanning a 1-year window.

    Methodology:
    - Spreads transactions across 365 days ending at `end_date`.
    - Applies higher sampling weights to weekends (Friday–Sunday) and Q4
      holiday shopping months (November–December).
    - Models realistic intraday shopping hours peaking between 11:00 AM and 7:00 PM.
    """
    days = [end_date - timedelta(days=d) for d in range(365)]
    day_weights = []

    for day in days:
        weight = 1.0
        # Weekend boost (Friday=4, Saturday=5, Sunday=6)
        if day.weekday() in (4, 5, 6):
            weight *= 1.35
        # Holiday season boost (November & December)
        if day.month in (11, 12):
            weight *= 1.50
        day_weights.append(weight)

    day_weights = np.array(day_weights) / sum(day_weights)
    chosen_days = np.random.choice(days, size=num_records, p=day_weights)

    # Intraday hour weights (store hours 8 AM to 10 PM, peaking mid-afternoon)
    hours = np.arange(8, 23)
    hour_probs = np.array([0.02, 0.04, 0.06, 0.08, 0.09, 0.09, 0.08, 0.08, 0.09, 0.10, 0.10, 0.08, 0.05, 0.03, 0.01])
    hour_probs /= hour_probs.sum()

    chosen_hours = np.random.choice(hours, size=num_records, p=hour_probs)
    chosen_minutes = np.random.randint(0, 60, size=num_records)
    chosen_seconds = np.random.randint(0, 60, size=num_records)

    timestamps = [
        datetime(d.year, d.month, d.day, int(h), int(m), int(s))
        for d, h, m, s in zip(chosen_days, chosen_hours, chosen_minutes, chosen_seconds)
    ]
    timestamps.sort()
    return timestamps


def generate_quantities_prices_discounts(unit_prices: np.ndarray, timestamps: list[datetime]) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Generate realistic order quantities, applied discount rates, and final line totals.

    Methodology:
    - Quantities follow a shifted geometric distribution (mostly 1-2 items,
      occasionally bulk orders up to 10 items).
    - Discounts are mostly 0%, with promotional tiers (5%, 10%, 15%, 20%, 30%)
      occurring more frequently during November/December promotional periods.
    - Total amounts are calculated after applying the discount rate.
    """
    num_records = len(unit_prices)

    # Geometric distribution clipped to [1, 10] items per transaction
    quantities = np.clip(np.random.geometric(p=0.65, size=num_records), 1, 10)

    discount_tiers = np.array([0.0, 0.05, 0.10, 0.15, 0.20, 0.30])
    regular_probs = np.array([0.72, 0.10, 0.08, 0.05, 0.03, 0.02])
    holiday_probs = np.array([0.45, 0.12, 0.15, 0.12, 0.10, 0.06])

    discounts = np.zeros(num_records)
    for idx, ts in enumerate(timestamps):
        probs = holiday_probs if ts.month in (11, 12) else regular_probs
        discounts[idx] = np.random.choice(discount_tiers, p=probs)

    total_amounts = np.round(unit_prices * quantities * (1.0 - discounts), 2)
    return quantities, discounts, total_amounts


def generate_transactions(
    products_df: pd.DataFrame,
    stores_df: pd.DataFrame,
    customer_ids: np.ndarray,
    num_records: int = 50000,
) -> pd.DataFrame:
    """
    Assemble the synthetic retail transactions table combining products, stores, and customers.

    Methodology:
    - Samples products using `popularity_weight` so bestsellers appear more frequently.
    - Samples stores using `traffic_weight` so Flagship stores process more transactions.
    - Generates chronological timestamps over a 1-year period and computes final pricing.
    """
    end_date = datetime(2026, 11, 17, 23, 59, 59)
    timestamps = generate_timestamps(num_records, end_date)

    sampled_product_indices = np.random.choice(
        products_df.index,
        size=num_records,
        p=products_df["popularity_weight"].values,
    )
    sampled_products = products_df.iloc[sampled_product_indices].reset_index(drop=True)

    sampled_store_ids = np.random.choice(
        stores_df["store_id"].values,
        size=num_records,
        p=stores_df["traffic_weight"].values,
    )
    sampled_customers = np.random.choice(customer_ids, size=num_records)

    unit_prices = sampled_products["unit_price"].values
    quantities, discounts, total_amounts = generate_quantities_prices_discounts(unit_prices, timestamps)

    transactions_df = pd.DataFrame({
        "transaction_id": [f"TXN-{i:07d}" for i in range(1, num_records + 1)],
        "timestamp": [ts.strftime("%Y-%m-%d %H:%M:%S") for ts in timestamps],
        "store_id": sampled_store_ids,
        "customer_id": sampled_customers,
        "product_id": sampled_products["product_id"].values,
        "quantity": quantities,
        "unit_price": unit_prices,
        "discount_rate": discounts,
        "total_amount": total_amounts,
    })


    return transactions_df


def generate_inventory(products_df, stores_df, transactions_df):
    """Generate store-level inventory and stock replenishment tables from product and transaction data."""
    sales_summary = transactions_df.groupby(['store_id', 'product_id'], as_index=False)['quantity'].sum().rename(columns={'quantity': 'units_sold_12m'})
    all_pairs = pd.MultiIndex.from_product([stores_df['store_id'].unique(), products_df['product_id'].unique()], names=['store_id', 'product_id']).to_frame(index=False)
    sampled_unstocked = all_pairs.sample(frac=0.25, random_state=RANDOM_SEED)
    inventory_df = pd.merge(pd.concat([sales_summary[['store_id', 'product_id']], sampled_unstocked]).drop_duplicates(), sales_summary, on=['store_id', 'product_id'], how='left')
    inventory_df['units_sold_12m'] = inventory_df['units_sold_12m'].fillna(0).astype(int)
    monthly_velocity = np.ceil(inventory_df['units_sold_12m'] / 12.0).astype(int)
    inventory_df['reorder_point'] = np.maximum(5, monthly_velocity * 2)
    stock_factors = np.random.uniform(0.1, 3.5, size=len(inventory_df))
    low_stock_mask = np.random.random(size=len(inventory_df)) < 0.08
    stock_factors[low_stock_mask] = np.random.uniform(0.0, 0.4, size=low_stock_mask.sum())
    inventory_df['stock_on_hand'] = np.round(inventory_df['reorder_point'] * stock_factors).astype(int)
    inventory_df['needs_reorder'] = inventory_df['stock_on_hand'] <= inventory_df['reorder_point']
    inventory_df['last_updated'] = '2026-11-17'
    return inventory_df


def main():
    """Execute the full synthetic data generation pipeline and export CSVs to data/."""
    data_dir = Path(__file__).resolve().parent.parent / 'data'
    data_dir.mkdir(parents=True, exist_ok=True)
    print('Generating products, stores, transactions, and inventory...')
    products_df = generate_products(1000)
    stores_df = generate_stores(100)
    customer_ids = generate_customer_ids(12000)
    transactions_df = generate_transactions(products_df, stores_df, customer_ids, 50000)
    inventory_df = generate_inventory(products_df, stores_df, transactions_df)
    outputs = {'products.csv': products_df.drop(columns=['popularity_weight']), 'stores.csv': stores_df.drop(columns=['traffic_weight']), 'transactions.csv': transactions_df, 'inventory.csv': inventory_df}
    for name, df in outputs.items():
        path = data_dir / name
        df.to_csv(path, index=False)
        print(f'Saved {len(df):,} rows to {path}')


if __name__ == '__main__':
    main()
